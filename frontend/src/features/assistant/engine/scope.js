import { normalize } from './text.js';

/**
 * Границы помощника: он работает только с CRM ИТ Школы. Посторонние запросы — арифметика, код,
 * погода, развлечения — отсекаются сразу, без модели. Тот же список правил дублирует backend
 * (app/services/assistant.py → OFF_TOPIC), чтобы модель не отвечала на них и в режиме «ИИ».
 */
const OFF_TOPIC = [
  // Арифметика: «2+2», «сколько будет 7*8», «реши уравнение».
  /^[\s\d+\-*/×÷^().,=?%]*\d\s*[+\-*/×÷^%]\s*\d[\s\d+\-*/×÷^().,=?%]*$/,
  /сколько будет\s*\d|(реши|вычисли|посчитай)\s+(\d|уравнен|пример|задач|интеграл)|корень из|факториал|интеграл|производн/,
  // Программирование.
  /(python|питон|javascript|джаваскрипт|typescript|golang|kotlin|c\+\+|c#|php|регулярн[а-я]* выражен|regex)/,
  /(напиши|сгенерируй|создай|покажи|дай)\s+(мне\s+)?(код|скрипт|функци|класс|алгоритм|программу на|sql[- ]запрос)/,
  // Всё остальное, что к работе с вузами не относится.
  /(погод|анекдот|шутк|рецепт|стих|сочини|песн|гороскоп|курс (доллар|евро|валют|биткоин|рубл)|фильм|сериал|футбол|сочинени|реферат|эссе|переведи на (англ|немец|франц|китай)|translate)/,
];

export const OUT_OF_SCOPE_TEXT =
  'Я помогаю только с работой в системе ИТ Школы Ростелекома: отчёты, взаимодействия с вузами, этапы, статистика, контакты и справка. С этим вопросом не подскажу.';

export const OUT_OF_SCOPE_SUGGESTIONS = ['Что ты умеешь?', 'План на сегодня', 'Покажи просроченные'];

export const isOutOfScope = (message) => {
  const text = normalize(message).trim();
  return OFF_TOPIC.some((pattern) => pattern.test(text));
};
